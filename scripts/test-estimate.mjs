assert.equal(estimateShade({ ...base, operation: 'tdbu' }).cents, 17147);
assert.equal(estimateShade({ ...base, operation: 'motor' }).cents, 46202);
assert.equal(estimateShade({ ...base, operation: 'motor-tdbu', quantity: '2' }).cents, 104222);
